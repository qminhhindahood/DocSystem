CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE "User" (
  "id" TEXT PRIMARY KEY, "username" TEXT NOT NULL UNIQUE, "passwordHash" TEXT NOT NULL,
  "role" TEXT NOT NULL DEFAULT 'user', "isDisabled" BOOLEAN NOT NULL DEFAULT false,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL
);
CREATE TABLE "UserLLMConfig" (
  "id" TEXT PRIMARY KEY, "userId" TEXT NOT NULL UNIQUE REFERENCES "User"("id") ON DELETE CASCADE,
  "provider" TEXT NOT NULL, "baseUrl" TEXT NOT NULL, "model" TEXT NOT NULL,
  "encryptedApiKey" TEXT NOT NULL, "apiKeyIv" TEXT NOT NULL, "apiKeyAuthTag" TEXT NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL
);
CREATE TABLE "Document" (
  "id" TEXT PRIMARY KEY, "docType" TEXT NOT NULL, "docNumber" TEXT, "title" TEXT NOT NULL,
  "content" TEXT NOT NULL, "status" TEXT NOT NULL DEFAULT 'draft',
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL,
  "publishedAt" TIMESTAMP(3)
);
CREATE TABLE "Chunk" (
  "id" TEXT PRIMARY KEY, "documentId" TEXT NOT NULL REFERENCES "Document"("id") ON DELETE CASCADE,
  "level" INTEGER NOT NULL, "article" TEXT, "clause" TEXT, "point" TEXT,
  "content" TEXT NOT NULL, "embedding" vector(1024), "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "Feedback" (
  "id" TEXT PRIMARY KEY, "documentId" TEXT NOT NULL REFERENCES "Document"("id") ON DELETE CASCADE,
  "originalContent" TEXT NOT NULL, "editedContent" TEXT NOT NULL, "diff" JSONB NOT NULL DEFAULT '{}',
  "approvedForTraining" BOOLEAN NOT NULL DEFAULT false, "approvedForRag" BOOLEAN NOT NULL DEFAULT false,
  "reviewStatus" TEXT NOT NULL DEFAULT 'pending', "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "Template" (
  "id" TEXT PRIMARY KEY, "name" TEXT NOT NULL, "docType" TEXT NOT NULL UNIQUE,
  "header" TEXT NOT NULL, "signatureBlock" TEXT NOT NULL, "isActive" BOOLEAN NOT NULL DEFAULT true,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL
);
CREATE TABLE "TrainingJob" (
  "id" TEXT PRIMARY KEY, "jobId" TEXT NOT NULL UNIQUE, "status" TEXT NOT NULL DEFAULT 'created',
  "threshold" INTEGER NOT NULL DEFAULT 50, "sampleCount" INTEGER NOT NULL DEFAULT 0,
  "filters" JSONB NOT NULL DEFAULT '{}', "progress" INTEGER NOT NULL DEFAULT 0,
  "epoch" INTEGER NOT NULL DEFAULT 0, "totalEpochs" INTEGER NOT NULL DEFAULT 10,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL
);
CREATE TABLE "ModelVersion" (
  "id" TEXT PRIMARY KEY, "baseModel" TEXT NOT NULL, "version" TEXT NOT NULL UNIQUE,
  "status" TEXT NOT NULL DEFAULT 'candidate', "isActivated" BOOLEAN NOT NULL DEFAULT false,
  "trainingJobId" TEXT REFERENCES "TrainingJob"("id") ON DELETE SET NULL,
  "feedbackCount" INTEGER NOT NULL DEFAULT 0, "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL
);
